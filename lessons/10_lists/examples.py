# Список — кілька значень між квадратними дужками.
items = ["хліб", "молоко"]
print(items[0])  # хліб: перший елемент має індекс 0.
print(len(items))  # 2: рахуємо елементи, а не символи.
items.append("чай")  # Додаємо значення в кінець самого списку.
print(items[-1])  # чай: -1 означає останній елемент.
items.remove("молоко")  # Видаляємо наявне значення, не номер.
for item in items:
    print(item)  # Після видалення побачимо хліб і чай.
# Помилка: items[5] тут не існує. remove("кава") теж дало б помилку.
