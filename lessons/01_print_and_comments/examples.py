# print() показує значення; результат видно в терміналі після запуску.
print("Ранок")  # Лапки кажуть Python, що це саме текст.
print(7)  # Без лапок це число; на екрані теж буде 7.
print("7")  # На екрані так само 7, але для Python це текст, не число.
# Наступний рядок — тільки пояснення. Він нічого не виводить.
# Типова помилка: print(Ранок) без лапок шукає змінну з таким ім'ям.
