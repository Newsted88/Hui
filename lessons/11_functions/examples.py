# def створює функцію, але її тіло поки що не виконується.
def double(number):
    # Під час виклику аргумент потрапить у параметр number.
    result = number * 2  # result — локальна змінна: живе всередині цього виклику.
    return result  # Повертаємо число до місця виклику й завершуємо функцію.

print("До виклику")
answer = double(4)  # 1. number стає 4; 2. result стає 8; 3. answer отримує 8.
print(answer)  # 8: print показує повернене значення.
print(double(6))  # Новий виклик має свої number і result; побачимо 12.

def greet(name):
    print(f"Привіт, {name}!")  # Лише показує текст; нічого корисного не повертає.

greet("Оля")  # Аргумент "Оля" передається параметру name.
# Помилка: поза double не можна звертатися до локальної змінної result.
# Якщо потрібне число для подальших обчислень, використовуйте return, а не print.
