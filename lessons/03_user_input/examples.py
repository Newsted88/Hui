# Цей приклад просить дві відповіді. Вводьте ім'я, потім ціле число.
name = input("Як вас звати? ")  # input показує запитання і чекає Enter.
print("Вітаю, " + name)  # input повертає текст, тому тут текст поєднується з текстом.
age_text = input("Скільки вам років? ")  # Навіть цифри приходять як str.
age = int(age_text)  # int перетворює, наприклад, текст "12" на число 12.
print(type(age))  # Очікуємо <class 'int'>.
print("Дякую за відповідь!")
# Якщо ввести слово замість цифр, int покаже ValueError: перетворення неможливе.
