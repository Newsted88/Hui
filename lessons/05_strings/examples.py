# Рядок — послідовність символів. Пробіл теж символ.
word = "кіт"
print(len(word))  # 3: len рахує кількість символів.
print(word[0])  # к: Python починає рахувати позиції з нуля.
print(word[-1])  # т: -1 вказує на останній символ.
print("Добрий " + "день")  # + поєднує тексти; пробіл ми додали самі.
name = "  Оля  "
clean_name = name.strip()  # Прибираємо пробіли тільки на краях; отримуємо новий рядок.
print(clean_name.upper())  # ОЛЯ: upper повертає варіант великими літерами.
print(clean_name.lower())  # оля: lower повертає варіант малими літерами.
print(f"Привіт, {clean_name}!")  # f вставляє значення змінної між фігурними дужками.
# Помилка: word[3] не існує, бо індекси трьох символів — 0, 1, 2.
