# Для чисел Python виконує звичні арифметичні дії.
print(7 + 2)  # 9: додавання.
print(7 - 2)  # 5: віднімання.
print(7 * 2)  # 14: множення; зірочка означає «помножити».
print(7 / 2)  # 3.5: звичайне ділення повертає float.
print(7 // 2)  # 3: скільки повних двійок міститься у 7.
print(7 % 2)  # 1: остача після утворення повних двійок.
print(2 ** 3)  # 8: два у третьому степені.
print(2 + 3 * 4)  # 14: множення виконується раніше.
print((2 + 3) * 4)  # 20: дужки змінюють порядок.
# Помилка: 7 / 0 викликало б ZeroDivisionError; цей рядок не запускаємо.
