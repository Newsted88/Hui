# if перевіряє логічне значення і виконує лише відповідний блок.
temperature = 15
if temperature > 20:  # Двокрапка починає блок умови.
    print("Тепло")  # Чотири пробіли означають: рядок належить if.
elif temperature >= 10:  # Перевіряємо це лише якщо попереднє було False.
    print("Прохолодно")  # Побачимо саме цей рядок: 15 >= 10.
else:  # Усі попередні перевірки були хибними.
    print("Холодно")
has_time = True
is_raining = False
if has_time:
    if is_raining:  # Вкладена умова перевіряється тільки за наявності часу.
        print("Візьміть парасольку")
    else:
        print("Можна гуляти")  # Побачимо цей рядок.
