# while перевіряє умову перед кожним повтором.
count = 1  # Початкове значення лічильника.
while count <= 3:
    print(count)  # Послідовно побачимо 1, 2, 3.
    count = count + 1  # Без зміни умова лишалася б істинною.
print("Готово")  # Цей рядок виконується після завершення циклу.
number = 0
while number < 6:
    number = number + 1  # Оновлюємо до можливого continue.
    if number == 2:
        continue  # Пропускаємо виведення 2, але повертаємося до умови.
    if number == 5:
        break  # Виходимо з циклу; 5 і 6 не виводяться.
    print(number)  # Побачимо 1, 3, 4.
# Якщо цикл не завершується, натисніть Ctrl+C і перевірте зміну лічильника.
