# Змінна зберігає значення під зрозумілим ім'ям.
cups = 2  # = присвоює 2 імені cups, а не перевіряє математичну рівність.
price = 12.5  # Крапка позначає дробову частину; тип цього значення — float.
drink = "чай"  # Лапки роблять значення текстом, тобто str.
is_hot = True  # True або False — логічний тип bool; пишемо з великої літери.
print(cups)  # Побачимо 2, бо Python дістає значення змінної.
print(type(price))  # Побачимо <class 'float'> — тип змінної price.
print(type(drink))  # Побачимо <class 'str'>.
print(type(is_hot))  # Побачимо <class 'bool'>.
cups = 3  # Нове присвоєння замінює попереднє значення.
print(cups)  # Тепер побачимо 3.
# Помилка: написати cup замість cups — такого імені тут немає.
